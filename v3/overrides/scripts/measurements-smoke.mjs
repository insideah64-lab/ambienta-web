import assert from 'node:assert/strict';
import fs from 'node:fs';
import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
try{
 const page=await browser.newPage({viewport:{width:1440,height:900},acceptDownloads:true});
 const errors=[];page.on('pageerror',x=>errors.push(String(x)));
 await page.goto('http://127.0.0.1:8787/v3/index.html?caso=diablillos#/monitoreo');
 const panel=page.locator('[data-measurements-panel]');
 await panel.locator('[data-measurement-empty=true]').waitFor();
 assert.equal(await panel.locator('[data-measurement-id]').count(),0);
 const domainBefore=await page.evaluate(()=>localStorage.getItem('ambienta-v2-diablillos-2026-demo'));
 await panel.getByLabel('Medida PGA').selectOption('MED-DIAB-001');
 await panel.getByLabel('Inspección opcional').selectOption('INSP-DIAB-001');
 await panel.getByLabel('Evidencia opcional').selectOption('EVID-D-001');
 const fill=async(name,value)=>panel.getByLabel(name,{exact:true}).fill(value);
 await fill('ID de muestra','MUESTRA-SINTETICA-01');
 await fill('Identificador de estación','EST-QA-SIMULADA');
 await panel.getByLabel('Matriz ambiental').selectOption('agua');
 await fill('Parámetro o analito','Parámetro sintético QA');
 await panel.getByLabel('Calificador del resultado').selectOption('quantified');
 await panel.getByLabel('Unidad').selectOption('mg/L');
 await fill('Valor numérico declarado','0.04');
 await fill('Límite de detección (LDM)','0.001');
 await fill('Límite de cuantificación (LCM)','0.005');
 await fill('Incertidumbre absoluta opcional','0.001');
 await fill('Fecha y hora de toma','2026-11-01T11:00');
 await fill('Fecha y hora de análisis opcional','2026-11-01T12:00');
 await fill('Método analítico','MÉTODO SIMULADO, sin laboratorio');
 await fill('Identificador del informe o fuente','LAB-QA-0001');
 await fill('Responsable declarante','Operador QA');
 await panel.getByRole('button',{name:'Registrar medición declarada'}).click();
 const first=panel.locator('[data-measurement-id=MUE-0001]');
 await first.waitFor();
 assert.equal(await first.getAttribute('data-measurement-status'),'evidence_reference_unverified');
 let raw=await page.evaluate(()=>localStorage.getItem('ambienta-v38-measurements-diablillos'));
 let book=JSON.parse(raw);
 assert.equal(book.entries[0].value,0.04);
 assert.equal(book.entries[0].evidenceId,'EVID-D-001');
 assert.equal(book.entries[0].inspectionId,'INSP-DIAB-001');
 assert.equal(book.revision,1);
 assert.equal(await page.evaluate(()=>localStorage.getItem('ambienta-v2-diablillos-2026-demo')),domainBefore);
 await panel.getByLabel('Medida PGA').selectOption('MED-DIAB-001');
 await fill('ID de muestra','MUESTRA-SINTETICA-02');
 await fill('Identificador de estación','EST-QA-SIMULADA');
 await fill('Parámetro o analito','Otro parámetro sintético');
 await panel.getByLabel('Calificador del resultado').selectOption('below_detection');
 await panel.getByLabel('Unidad').selectOption('µg/L');
 await fill('Límite de detección (LDM)','0.01');
 await fill('Fecha y hora de toma','2026-11-01T11:30');
 await fill('Método analítico','MÉTODO QA SIN DATOS REALES');
 await fill('Identificador del informe o fuente','LAB-QA-0002');
 await fill('Responsable declarante','Operador QA');
 await panel.getByRole('button',{name:'Registrar medición declarada'}).click();
 const second=panel.locator('[data-measurement-id=MUE-0002]');await second.waitFor();
 book=JSON.parse(await page.evaluate(()=>localStorage.getItem('ambienta-v38-measurements-diablillos')));
 assert.equal(book.entries[1].qualifier,'below_detection');
 assert.equal(book.entries[1].value,null);
 assert.equal(book.entries[1].detectionLimit,0.01);
 assert.equal(book.entries[1].evidenceId,null);
 const futureDownload=page.waitForEvent('download');
 await panel.getByRole('button',{name:'Exportar registro e historial JSON'}).click();
 const exported=JSON.parse(fs.readFileSync(await (await futureDownload).path(),'utf8'));
 assert.equal(exported.entries.length,2);
 assert.equal(exported.status,'LABORATORY_DEMO_NOT_VERIFIED');
 await first.getByRole('button',{name:'Anular con motivo'}).click();
 await panel.getByLabel('Motivo de anulación').fill('Duplicado de carga QA');
 await panel.getByLabel('Responsable de anulación').fill('Revisor QA');
 await panel.getByRole('button',{name:'Confirmar anulación'}).click();
 await panel.locator('[data-measurement-id=MUE-0001][data-measurement-status=voided]').waitFor();
 book=JSON.parse(await page.evaluate(()=>localStorage.getItem('ambienta-v38-measurements-diablillos')));
 assert.equal(book.entries[0].value,0.04);
 assert.equal(book.events[2].kind,'voided');
 assert.equal(book.events[2].reason,'Duplicado de carga QA');
 await page.reload();
 await page.locator('[data-measurement-id=MUE-0002]').waitFor();
 assert.equal(await page.locator('[data-measurement-id=MUE-0001]').getAttribute('data-measurement-status'),'voided');
 await page.evaluate(()=>{
  const k='ambienta-v38-measurements-diablillos';
  const v=JSON.parse(localStorage.getItem(k));
  v.entries[1].measureId='MED-INEXISTENTE';
  localStorage.setItem(k,JSON.stringify(v));
 });
 await page.reload();
 await page.locator('[data-measurements-panel=blocked]').waitFor();
 assert.equal(await page.getByRole('button',{name:'Registrar medición declarada'}).count(),0);
 assert.equal(await page.evaluate(()=>localStorage.getItem('ambienta-v2-diablillos-2026-demo')),domainBefore);
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({result:'PASS',manualResults:2,censoredNotZero:true,
  auditVoid:true,domainUnchanged:true,persistence:true,tamperBlocked:true,jsErrors:0}));
}finally{await browser.close();}
